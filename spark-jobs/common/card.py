"""Renders the dataset card (spec v2 section 6.2) from the numbers the gold load actually loaded.

The card is generated, never hand-written: every count in it comes from the rows written to `agg_*` in the same run.
That is the only way it can be trusted, and it is also why the renderer takes plain Python values (already collected
on the driver) rather than DataFrames — a card that can be built by a unit test is a card whose numbers can be
checked by hand.
"""

from __future__ import annotations

from typing import Any, Mapping, Sequence

#: The limitations every card must state. They are facts about the pipeline, not disclaimers, so they are part of the
#: renderer rather than something a caller may forget.
KNOWN_LIMITATIONS: tuple[str, ...] = (
    "**Snippets, not files.** The findings event carries the flagged lines, so a triple pairs those snippets. It is "
    "not a whole-file before/after pair, and `snippet_changed = false` marks the triples where the resolved finding's "
    "snippet is identical on both sides — the fix happened elsewhere in the file or the code did not change.",
    "**Commits, not days.** `commits_until_resolved` is a first-parent distance: the findings event has no commit "
    "timestamp, so no duration is claimed. When a finding is already present at the root of the mined window its "
    "distance is a *lower bound*; those triples are counted in `introductions_unobserved` and any average has to "
    "exclude them rather than silently include a truncated value.",
    "**Event time on the trend axis.** The quality trend is bucketed by when a revision was analysed, not by when it "
    "was committed.",
    "**Measured lines are per distinct file content** for a repository, so re-analysing the same revision does not "
    "inflate the per-KLOC denominators.",
    "**Dependency impact is not measured** until the relationship table of Phase 8 exists; it carries weight 0 in the "
    "hotspot score and `weight_sum_measured` records the divisor that was really used.",
    "**Licences are whatever the operational `repository` row says.** Nothing in the pipeline detects a LICENSE file "
    "yet, so an empty licence column means unknown, not permissive.",
    "**Splits are by repository**, so no commit of one repository can appear on two sides of the train/test boundary.",
)


def render_dataset_card(summary: Mapping[str, Any]) -> str:
    """Markdown dataset card for one gold snapshot."""

    lines: list[str] = []
    version = summary["dataset_version"]
    generated_at = summary["generated_at"]
    repository_rows = list(summary.get("repositories") or [])

    lines.append("# BCosmos fix-triple dataset card")
    lines.append("")
    lines.append(
        "Generated by `spark-jobs/batch/load_gold.py` from the rows it wrote to the `agg_*` tables. Do not edit by "
        "hand: a hand-edited number is a number nobody can reproduce."
    )
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("|---|---|")
    lines.append(f"| `dataset_version` | `{version}` |")
    lines.append(f"| Generated at (UTC) | {generated_at} |")
    lines.append(f"| Triples | {_number(summary.get('triples'))} |")
    lines.append(f"| Repositories | {_number(len(repository_rows))} |")
    lines.append(f"| Splits | {_split_names(summary.get('splits', []))} |")
    lines.append(f"| Rules covered | {_number(summary.get('rules'))} |")
    lines.append(f"| Max changed lines filter | {_number(summary.get('max_changed_lines'))} |")
    lines.append(f"| Triples with a visible snippet change | {_number(summary.get('snippet_changed'))} |")
    lines.append(f"| Introductions at the window root (lower-bound distances) | "
                 f"{_number(summary.get('introductions_unobserved'))} |")
    lines.append("")

    lines.append("## Splits")
    lines.append("")
    lines.extend(_table(
        ("Split", "Triples", "Repositories", "Rules", "Visible snippet change", "Lower-bound distances"),
        [
            (
                split.get("split"),
                _number(split.get("triples")),
                _number(split.get("repositories")),
                _number(split.get("rules")),
                _number(split.get("snippet_changed")),
                _number(split.get("introductions_unobserved")),
            )
            for split in summary.get("splits", [])
        ],
    ))
    lines.append("")

    lines.append("## Repositories and licences")
    lines.append("")
    lines.extend(_table(
        ("Split", "Repository", "Licence", "Triples"),
        [
            (
                repository.get("split"),
                repository.get("repository_name") or f"repository {repository.get('repository_id')}",
                repository.get("license_spdx") or "unknown",
                _number(repository.get("triples")),
            )
            for repository in repository_rows
        ],
    ))
    lines.append("")
    unknown = summary.get("repositories_without_license", 0)
    lines.append(f"Licence unknown for **{_number(unknown)}** of {_number(len(repository_rows))} repositories.")
    lines.append("")

    if summary.get("rules_covered"):
        lines.append("## Rules covered")
        lines.append("")
        lines.extend(_table(
            ("Rule", "Triples"),
            [(row.get("rule_id"), _number(row.get("triples"))) for row in summary["rules_covered"]],
        ))
        lines.append("")

    lines.append("## Filters applied")
    lines.append("")
    lines.append(f"- max changed lines: `{_number(summary.get('max_changed_lines'))}`")
    lines.append("- target finding fingerprint present before and absent after")
    lines.append("- no new finding of the same rule in the later revision")
    lines.append("- both revisions parsed")
    lines.append("- the file content changed between the two revisions")
    lines.append(f"- drill-down rows loaded: the most recent `{_number(summary.get('drilldown_commits'))}` commits per "
                 "repository")
    lines.append("")

    lines.append("## Pipeline counts")
    lines.append("")
    lines.extend(_table(
        ("Statistic", "Value"),
        [(key, _number(value)) for key, value in sorted(summary.get("pipeline_stats", {}).items())],
    ))
    lines.append("")

    lines.append("## Known limitations")
    lines.append("")
    for limitation in KNOWN_LIMITATIONS:
        lines.append(f"- {limitation}")
    lines.append("")

    return "\n".join(lines) + "\n"


def _table(headers: Sequence[str], rows: Sequence[Sequence[Any]]) -> list[str]:
    if not rows:
        return ["_None._"]
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        lines.append("| " + " | ".join("" if cell is None else str(cell) for cell in row) + " |")
    return lines


def _number(value: Any) -> str:
    if value is None:
        return "0"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:g}"
    return f"{value:,}"


def _split_names(splits: Sequence[Mapping[str, Any]]) -> str:
    return ", ".join(str(split.get("split")) for split in splits) or "none"
