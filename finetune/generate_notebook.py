def generate_notebook(output_path: str = "finetune_qlora.ipynb") -> None:
    """Generates the .ipynb file from NOTEBOOK_CELLS."""
    import json as _json
    import os

    def make_cell(cell_def: dict) -> dict:
        if cell_def["type"] == "markdown":
            return {
                "cell_type": "markdown",
                "metadata": {},
                "source": cell_def["source"],
            }
        return {
            "cell_type": "code",
            "execution_count": None,
            "metadata": {},
            "outputs": [],
            "source": cell_def["source"],
        }

    notebook = {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python", "version": "3.11.0"},
            "accelerator": "GPU",
            "colab": {"provenance": []},
        },
        "cells": [make_cell(c) for c in NOTEBOOK_CELLS],
    }

    out = os.path.join(os.path.dirname(__file__), output_path)
    with open(out, "w", encoding="utf-8") as f:
        _json.dump(notebook, f, indent=1, ensure_ascii=False)
    print(f"Generated {out}")


if __name__ == "__main__":
    generate_notebook()
